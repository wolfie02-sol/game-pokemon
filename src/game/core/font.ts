export const CHAR_W = 6;
export const GLYPH_H = 9;

type Atlas = HTMLCanvasElement;
const atlasCache = new Map<string, Atlas>();
const glyphIndex = new Map<string, number>();
const glyphList = Object.keys(G);
glyphList.forEach((k, i) => glyphIndex.set(k, i));

function buildAtlas(color: string): Atlas {
  const c = document.createElement('canvas');
  c.width = glyphList.length * 6;
  c.height = GLYPH_H;
  const x = c.getContext('2d')!;
  x.fillStyle = color;
  glyphList.forEach((k, gi) => {
    const rows = G[k].split('|');
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') x.fillRect(gi * 6 + rx, ry, 1, 1);
    });
  });
  return c;
}

function atlas(color: string): Atlas {
  let a = atlasCache.get(color);
  if (!a) {
    a = buildAtlas(color);
    atlasCache.set(color, a);
  }
  return a;
}

/** Draw a single line of text. Unknown characters render as blanks. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color = '#1a1626') {
  const a = atlas(color);
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text) {
    const gi = glyphIndex.get(ch);
    if (gi !== undefined) ctx.drawImage(a, gi * 6, 0, 6, GLYPH_H, cx, cy, 6, GLYPH_H);
    cx += CHAR_W;
  }
}

/** Text with a 1px drop shadow, used on colourful backgrounds. */
export function drawTextShadow(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  shadow: string,
) {
  drawText(ctx, text, x + 1, y + 1, shadow);
  drawText(ctx, text, x, y, color);
}

/** Text scaled by an integer factor (for logos and titles). */
export function drawTextScaled(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
) {
  const a = atlas(color);
  let cx = x;
  for (const ch of text) {
    const gi = glyphIndex.get(ch);
    if (gi !== undefined) ctx.drawImage(a, gi * 6, 0, 6, GLYPH_H, cx, y, 6 * scale, GLYPH_H * scale);
    cx += CHAR_W * scale;
  }
}

export function textWidth(text: string): number {
  return [...text].length * CHAR_W;
}

/** Word-wrap into lines of at most `max` characters. Honours explicit \n. */
export function wrap(text: string, max: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      if (!line.length) line = w;
      else if ((line + ' ' + w).length <= max) line += ' ' + w;
      else {
        out.push(line);
        line = w;
      }
      while (line.length > max) {
        out.push(line.slice(0, max));
        line = line.slice(max);
      }
    }
    out.push(line);
  }
  return out;
}

export function padLeft(s: string | number, n: number): string {
  const str = String(s);
  return str.length >= n ? str : ' '.repeat(n - str.length) + str;
}
